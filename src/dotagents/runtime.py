def capability_index_payload(index: CapabilityIndex) -> dict[str, object]:
  return {
    "schema_version": index.schema_version,
    "skills": [capability_skill_payload(skill) for skill in index.skills],
    "compiled_groups": [capability_group_payload(group) for group in index.compiled_groups],
  }


def capability_skill_payload(skill: CapabilitySkill) -> dict[str, object]:
  payload: dict[str, object] = {
    "name": skill.name,
    "kind": skill.kind,
    "path": skill.path,
    "status": skill.status,
  }
  if skill.group_id is not None:
    payload["group_id"] = skill.group_id
  if skill.compiler is not None:
    payload["compiler"] = skill.compiler
  if skill.messages:
    payload["messages"] = list(skill.messages)
  return payload


def capability_group_payload(group: CapabilityGroup) -> dict[str, object]:
  return {
    "id": group.id,
    "compiler": group.compiler,
    "output_prefix": group.output_prefix,
    "status": group.status,
    "messages": list(group.messages),
  }


def compiled_group_status(repo_root: Path, group: BuildGroup) -> CompiledGroupStatus:
  messages: list[str] = []
  for artifact in group.artifacts:
    message = compiled_artifact_status_message(repo_root, artifact)
    if message:
      messages.append(message)
  for source in group.sources:
    message = compiled_source_staleness_message(repo_root, source)
    if message:
      messages.append(message)
  return CompiledGroupStatus(group.id, compiled_status_from_messages(messages), tuple(messages))


def compiled_artifact_status_message(
  repo_root: Path,
  artifact: BuildManifestEntry,
) -> str | None:
  try:
    destination = validate_compiled_artifact_destination(artifact.artifact)
  except DotagentsError as exc:
    return f"compiled artifacts invalid: {exc}"
  path = repo_root / destination
  if not path.is_file():
    return f"compiled artifact missing: {destination}"
  actual_sha256 = sha256_file(path)
  if actual_sha256 != artifact.sha256:
    return f"compiled artifact changed since build manifest: {destination}"
  return None


def compiled_status_from_messages(
  messages: list[str],
) -> CapabilityStatus:
  if not messages:
    return "ok"
  if any("invalid" in message or "error" in message for message in messages):
    return "invalid"
  if any("missing" in message for message in messages):
    return "missing"
  return "stale"


def compiled_source_staleness_message(repo_root: Path, source: BuildSource) -> str | None:
  if source.kind == "file":
    try:
      reference = validate_relative_output_path(source.reference)
    except CompilerError as exc:
      return f"compiled artifacts stale: {exc}"
    return compiled_path_staleness(
      repo_root,
      reference,
      source.version,
      missing_label="file source",
      hash_label="file",
      changed_label="file source",
    )
  if source.kind == "package":
    if source.reference == "dotagents" and source.version != package_version():
      return "compiled artifacts stale: dotagents package changed"
    return None
  if source.kind == "variables":
    return None
  if source.kind in {"mcp", "mcp-command", "github-skill"}:
    return None
  if source.kind == "mcp-metadata":
    try:
      _, _, reference = parse_mcp_metadata_reference(source.reference)
      reference = validate_relative_output_path(reference)
    except CompilerError as exc:
      return f"compiled artifacts stale: {exc}"
    return compiled_path_staleness(
      repo_root,
      reference,
      source.version,
      missing_label="MCP metadata source",
      hash_label="MCP metadata source",
      changed_label="MCP metadata source",
    )
  if source.kind == "template":
    return compiled_file_like_source_staleness(repo_root, source, "template source")
  if source.kind == "template-variables":
    return compiled_file_like_source_staleness(repo_root, source, "template variables")
  return f"compiled artifacts stale: unrecognized source kind: {source.kind}"


def compiled_file_like_source_staleness(
  repo_root: Path,
  source: BuildSource,
  label: str,
) -> str | None:
  try:
    _, reference = parse_template_source_reference(source.reference)
    if reference == "<inline>":
      return None
    reference = validate_relative_output_path(reference)
  except CompilerError as exc:
    return f"compiled artifacts stale: {exc}"
  return compiled_path_staleness(
    repo_root,
    reference,
    source.version,
    missing_label=label,
    hash_label=label,
    changed_label=label,
  )


def compiled_path_staleness(
  repo_root: Path,
  reference: str,
  expected_version: str,
  missing_label: str,
  hash_label: str,
  changed_label: str,
) -> str | None:
  path = repo_root / reference
  if not path.is_file():
    return f"compiled artifacts stale: {missing_label} missing: {reference}"
  try:
    current_version = sha256_file(path)
  except OSError as exc:
    return f"compiled artifacts stale: cannot hash {hash_label}: {reference}: {exc}"
  if current_version != expected_version:
    return f"compiled artifacts stale: {changed_label} changed: {reference}"
  return None


def remove_stale_links(
  repo_root: Path,
  previous_lock: RuntimeLock | None,
  locked_links: list[LockedLink],
  operation_log: OperationLog,
) -> list[LockedLink]:
  if previous_lock is None:
    return []

  current_destinations = {link.destination for link in locked_links}
  skipped_links: list[LockedLink] = []
  prune_candidates: set[Path] = set()
  for link in previous_lock.links:
    if link.destination in current_destinations:
      continue
    destination = repo_root / link.destination
    if not remove_link_with_backup(repo_root, link, destination, operation_log):
      skipped_links.append(link)
    collect_parents(repo_root, destination, prune_candidates)

  prune_empty_dirs(repo_root, prune_candidates, operation_log)
  return skipped_links


def remove_stale_assets(
  repo_root: Path,
  previous_lock: RuntimeLock | None,
  locked_assets: list[LockedAsset],
  operation_log: OperationLog,
) -> list[LockedAsset]:
  if previous_lock is None:
    return []

  current_destinations = {asset.destination for asset in locked_assets}
  skipped_assets: list[LockedAsset] = []
  prune_candidates: set[Path] = set()
  for asset in previous_lock.assets:
    if asset.destination in current_destinations:
      continue
    destination = repo_root / asset.destination
    if not remove_locked_asset(repo_root, destination, asset.sha256, operation_log):
      skipped_assets.append(asset)
    collect_parents(repo_root, destination, prune_candidates)
  prune_empty_dirs(repo_root, prune_candidates, operation_log)
  return skipped_assets


def runtime_destination(runtime_dir: Path, entry: SyncEntry) -> Path:
  if entry.source == "skills":
    return runtime_dir / "skills"
  source = Path(entry.source)
  first = source.parts[0]
  if first in {"scripts", "skills", "hooks"}:
    return runtime_dir / source
  if entry.provider and first == entry.provider:
    suffix = Path(*source.parts[1:]) if len(source.parts) > 1 else Path()
    return runtime_dir / "providers" / entry.provider / suffix
  raise DotagentsError(f"unsupported manifest source root: {entry.source}")


def render_rules(
  runtime_context: RuntimeContext,
  operation_log: OperationLog,
  known_backup: BackupRecord | None = None,
) -> BackupRecord | None:
  """Write `.rules` and return the backup record from `write_text`, if any.

  Raises:
    DotagentsError: if the bundled `rules/rules.md` can't be read, or (via `write_text`)
      if `.rules` is a symlink or a `.rules.bak` conflict already exists.
  """
  shared_rules = runtime_context.asset_root / "rules" / "rules.md"
  try:
    shared = shared_rules.read_text(encoding="utf-8").rstrip()
  except OSError as exc:
    raise DotagentsError(f"cannot read bundled rules file: {shared_rules}") from exc
  chunks = ["<!-- Shared agent rules from dotagents package rules/rules.md -->", "", shared]
  local = runtime_context.repo_root / ".rules.local"
  if local.exists():
    chunks.extend(
      [
        "",
        "",
        "<!-- Local repo rules from .rules.local -->",
        "",
        local.read_text(encoding="utf-8").rstrip(),
      ]
    )
  return write_text(
    runtime_context.repo_root,
    runtime_context.repo_root / ".rules",
    "\n".join(chunks) + "\n",
    operation_log,
    backup_existing=runtime_context.is_global or runtime_context.self_host,
    known_backup=known_backup,
  )


def lock_entries(
  repo_root: Path, source: Path, destination: Path, source_name: str
) -> list[LockedAsset]:
  if source.is_file():
    return [LockedAsset(source_name, relative(repo_root, destination), sha256_file(source))]

  entries: list[LockedAsset] = []
  for path in sorted(source.rglob("*")):
    if path.is_file():
      relative_path = path.relative_to(source)
      entries.append(
        LockedAsset(
          str(Path(source_name) / relative_path),
          relative(repo_root, destination / relative_path),
          sha256_file(path),
        )
      )
  return entries


def unique_locked_assets(locked_assets: list[LockedAsset]) -> list[LockedAsset]:
  unique: dict[tuple[str, str], LockedAsset] = {}
  for asset in locked_assets:
    unique[(asset.source, asset.destination)] = asset
  return list(unique.values())


def validate_locked_asset_destinations_unique(locked_assets: list[LockedAsset]) -> None:
  assets_by_destination: dict[str, LockedAsset] = {}
  for asset in locked_assets:
    existing = assets_by_destination.get(asset.destination)
    if existing is not None and existing.source != asset.source:
      raise DotagentsError(
        "managed asset destination collision: "
        f"{asset.destination} from {existing.source} and {asset.source}"
      )
    assets_by_destination[asset.destination] = asset


def unique_locked_links(locked_links: list[LockedLink]) -> list[LockedLink]:
  unique: dict[str, LockedLink] = {}
  for link in locked_links:
    unique[link.destination] = link
  return list(unique.values())


def copy_path(
  repo_root: Path, source: Path, destination: Path, operation_log: OperationLog
) -> None:
  if source.is_dir():
    for path in sorted(source.rglob("*")):
      if path.is_file():
        copy_file(repo_root, path, destination / path.relative_to(source), operation_log)
    return
  copy_file(repo_root, source, destination, operation_log)


def copy_file(
  repo_root: Path, source: Path, destination: Path, operation_log: OperationLog
) -> None:
  resolve_parent_within_root(repo_root, destination)
  if destination.is_symlink():
    raise DotagentsError(
      f"refusing to replace symlink with managed file: {relative(repo_root, destination)}"
    )
  if (
    destination.exists()
    and destination.is_file()
    and filecmp.cmp(source, destination, shallow=False)
  ):
    operation_log.add(f"ok {relative(repo_root, destination)}")
    return
  if operation_log.dry_run:
    operation_log.add(f"would copy {relative(repo_root, destination)}")
    return
  destination.parent.mkdir(parents=True, exist_ok=True)
  shutil.copy2(source, destination)
  operation_log.add(f"copied {relative(repo_root, destination)}")


def write_generated_file(
  repo_root: Path, destination: Path, content: str, operation_log: OperationLog
) -> None:
  """Same symlink-guard, skip-if-identical, and dry-run behavior as `copy_file`, for content
  that only exists in memory (e.g. a merged settings file) rather than as a source file.

  Writes raw UTF-8 bytes rather than using text mode: `Path.write_text` applies platform
  newline translation (`\\n` -> `os.linesep`), which on Windows would make the on-disk bytes
  diverge from the LF-only content hashed into the lockfile, permanently failing doctor's
  drift check on every sync.
  """
  resolve_parent_within_root(repo_root, destination)
  if destination.is_symlink():
    raise DotagentsError(
      f"refusing to replace symlink with managed file: {relative(repo_root, destination)}"
    )
  content_bytes = content.encode("utf-8")
  if destination.exists() and destination.is_file() and destination.read_bytes() == content_bytes:
    operation_log.add(f"ok {relative(repo_root, destination)}")
    return
  if operation_log.dry_run:
    operation_log.add(f"would copy {relative(repo_root, destination)}")
    return
  destination.parent.mkdir(parents=True, exist_ok=True)
  destination.write_bytes(content_bytes)
  operation_log.add(f"copied {relative(repo_root, destination)}")


def merge_autonomy_fragment(
  base_content: str, fragment_content: str, fmt: Literal["json", "toml"]
) -> str:
  """Merge a permission fragment into a provider's base settings content.

  The fragment is expected to introduce only top-level keys the base file doesn't already
  define (e.g. `permissions` for Claude, `approval_policy`/`sandbox_mode` for Codex). That's
  enforced below rather than merely assumed, so a future fragment or base-file edit that
  redefines an existing key fails loudly instead of silently overwriting it.

  Raises:
    DotagentsError: if either side doesn't decode to a JSON/TOML object, or a fragment key
      collides with a base key.
  """
  if fmt == "json":
    base = _require_mapping(json.loads(base_content), "base settings content")
    fragment = _require_mapping(json.loads(fragment_content), "permission fragment")
    _reject_key_collision(base, fragment)
    return json.dumps({**base, **fragment}, indent=2) + "\n"

  # tomllib has no comment support, so a round trip through it would silently drop the
  # human-authored header comment at the top of e.g. codex/config.toml (mid-file comments
  # would be lost too, but no shipped fragment's base file has any). Preserving the leading
  # block keeps the merged output no worse than a plain copy for providers without autonomy set.
  lines = base_content.splitlines(keepends=True)
  header_lines: list[str] = []
  while lines and (lines[0].startswith("#") or not lines[0].strip()):
    header_lines.append(lines.pop(0))
  # A TOML document's top level always decodes to a dict, unlike JSON's `[]`/`null`/scalars,
  # but _require_mapping is applied uniformly rather than relying on that as an invariant.
  base = _require_mapping(tomllib.loads("".join(lines)), "base settings content")
  fragment = _require_mapping(tomllib.loads(fragment_content), "permission fragment")
  _reject_key_collision(base, fragment)
  return "".join(header_lines) + tomli_w.dumps({**base, **fragment})


def _require_mapping(value: object, description: str) -> dict[str, object]:
  if not isinstance(value, dict):
    raise DotagentsError(f"{description} must be a JSON/TOML object, got {type(value).__name__}")
  return cast(dict[str, object], value)


def _reject_key_collision(base: dict[str, object], fragment: dict[str, object]) -> None:
  colliding = sorted(set(base) & set(fragment))
  if colliding:
    raise DotagentsError(f"permission fragment redefines existing key(s): {', '.join(colliding)}")


def expected_managed_policy_content(runtime_context: RuntimeContext, asset_source: str) -> str:
  """Return what `sync_managed_provider_policy` would currently write for `asset_source`.

  Used by `doctor` to detect self-host staleness (source or fragment edited since the last
  sync) without depending on the runtime destination already existing.

  Raises:
    DotagentsError: if the base source or the resolved level's fragment file is missing, or
      either fails to parse as `fmt` — callers such as `doctor` rely on this catching every
      failure mode of a self-hosted maintainer's edit, not just the missing-fragment case.
  """
  provider, fmt = AUTONOMY_MANAGED_SOURCE_INFO[asset_source]
  level = runtime_context.autonomy.get(provider, DEFAULT_AUTONOMY_LEVEL)
  fragment_path = runtime_context.asset_root / provider / "permissions" / f"{level}.{fmt}"
  base_path = runtime_context.asset_root / asset_source
  if not base_path.exists():
    raise DotagentsError(f"missing base policy source for provider {provider}: {base_path}")
  if not fragment_path.exists():
    raise DotagentsError(f"no {level} permission fragment for provider {provider}: {fragment_path}")
  base_content = base_path.read_text(encoding="utf-8")
  fragment_content = fragment_path.read_text(encoding="utf-8")
  try:
    return merge_autonomy_fragment(base_content, fragment_content, fmt)
  except (json.JSONDecodeError, tomllib.TOMLDecodeError) as exc:
    raise DotagentsError(f"cannot parse provider policy for {provider}: {exc}") from exc


def sync_managed_provider_policy(
  runtime_context: RuntimeContext, asset_source: str, destination: Path, operation_log: OperationLog
) -> str:
  """Write `destination` as `asset_source` merged with the resolved autonomy fragment.

  Returns the merged content so the caller can hash what was (or would be) written without
  depending on `destination` existing yet — `--dry-run` never writes it.

  Raises:
    DotagentsError: if no fragment file exists for the resolved level.
  """
  merged_content = expected_managed_policy_content(runtime_context, asset_source)
  write_generated_file(runtime_context.repo_root, destination, merged_content, operation_log)
  return merged_content


def migrate_legacy_backup(
  repo_root: Path, known_backup: BackupRecord | None, backup_path: Path
) -> BackupRecord | None:
  """Upgrade a fingerprint-less backup record (carried forward from a v1 lock) to a real
  fingerprint computed from `backup_path`'s current on-disk state, or drop it if the backup
  is no longer a readable file or symlink.

  Without this, carrying `known_backup.fingerprint = None` forward unchanged into a
  freshly-written v2 lock would record `backup` with no `backup_fingerprint` — unreadable
  by the next `read_lock` call, which requires a fingerprint whenever a v2 lock has a backup.
  """
  if known_backup is None or known_backup.fingerprint is not None:
    return known_backup
  resolve_parent_within_root(repo_root, backup_path)
  if backup_path.is_symlink() or backup_path.is_file() or backup_path.is_dir():
    return BackupRecord(known_backup.path, backup_fingerprint(backup_path))
  return None


def migrate_legacy_link_backup(repo_root: Path, link: LockedLink) -> LockedLink:
  """Return `link` with its backup fingerprint migrated if it's a legacy (fingerprint-less)
  record, so writing it back into a v2 lock doesn't produce an unreadable entry.

  Needed anywhere a `LockedLink` read from an existing lock is written back out without
  going through `link_path` (which already migrates via `migrate_legacy_backup`) — e.g.
  `remove_provider`, which carries forward links it isn't touching.
  """
  if link.backup is None or link.backup_fingerprint is not None:
    return link
  migrated = migrate_legacy_backup(
    repo_root, BackupRecord(link.backup, link.backup_fingerprint), repo_root / link.backup
  )
  return LockedLink(
    destination=link.destination,
    target=link.target,
    provider=link.provider,
    backup=migrated.path if migrated else None,
    backup_fingerprint=migrated.fingerprint if migrated else None,
  )


def create_backup(
  repo_root: Path, destination: Path, backup: Path, operation_log: OperationLog
) -> BackupRecord:
  """Move `destination` aside to `backup`, recording the action in `operation_log`.

  Raises:
    DotagentsError: if `backup` already exists.
  """
  if backup.exists(follow_symlinks=False):
    raise DotagentsError(
      f"backup already exists: {relative(repo_root, backup)}; resolve manually and re-run"
    )
  backup_record = BackupRecord(relative(repo_root, backup), backup_fingerprint(destination))
  if operation_log.dry_run:
    operation_log.add(
      f"{WOULD_BACK_UP_PREFIX}{relative(repo_root, destination)} -> {relative(repo_root, backup)}"
    )
    operation_log.planned_backups.append((destination, backup))
  else:
    destination.rename(backup)
    operation_log.add(
      f"backed up {relative(repo_root, destination)} -> {relative(repo_root, backup)}"
    )
    operation_log.created_backups.append((destination, backup))
  return backup_record


def write_text(
  repo_root: Path,
  destination: Path,
  content: str,
  operation_log: OperationLog,
  backup_existing: bool = False,
  known_backup: BackupRecord | None = None,
) -> BackupRecord | None:
  """Return the backup record for `destination` if one was created or already tracked, else None.

  `known_backup` is the backup previously recorded in the lock, if any. A `.bak` file found
  on disk is only ever reported back if it was created by this call or was already tracked —
  an unrelated pre-existing `.bak` file is never adopted as dotagents-owned.

  Raises:
    DotagentsError: if `destination` is a symlink, or if a `.bak` file already exists at the
      backup path (conflict must be resolved manually).
  """
  backup = destination.parent / (destination.name + ".bak")
  resolve_parent_within_root(repo_root, destination)
  known_backup = migrate_legacy_backup(repo_root, known_backup, backup)
  if destination.is_symlink():
    raise DotagentsError(
      f"refusing to replace symlink with managed file: {relative(repo_root, destination)}"
    )
  if (
    destination.exists()
    and destination.is_file()
    and destination.read_text(encoding="utf-8") == content
  ):
    operation_log.add(f"ok {relative(repo_root, destination)}")
    return known_backup
  backup_record = known_backup
  backup_rel = relative(repo_root, backup)
  already_tracked = known_backup is not None and known_backup.path == backup_rel
  if backup_existing and destination.exists() and not already_tracked:
    backup_record = create_backup(repo_root, destination, backup, operation_log)
  if operation_log.dry_run:
    operation_log.add(f"would write {relative(repo_root, destination)}")
    return backup_record
  destination.write_text(content, encoding="utf-8")
  operation_log.add(f"wrote {relative(repo_root, destination)}")
  return backup_record


def link_path(
  repo_root: Path,
  source: Path,
  destination: Path,
  operation_log: OperationLog,
  known_backup: BackupRecord | None = None,
  backup_existing: bool = False,
) -> BackupRecord | None:
  """Return the backup record for `destination` if one was created or already tracked, else None.

  `known_backup` is the backup previously recorded in the lock, if any. A `.bak` file found
  on disk is only ever reported back if it was created by this call or was already tracked —
  an unrelated pre-existing `.bak` file is never adopted as dotagents-owned.
  `backup_existing` also backs up an already-correct symlink, which protects source-owned
  symlinks during self-hosting.

  Raises:
    DotagentsError: if a `.bak` file already exists at the backup path (conflict must be resolved manually).
  """
  resolve_parent_within_root(repo_root, destination)
  backup = destination.parent / (destination.name + ".bak")
  target = os.path.relpath(source, destination.parent)
  already_linked = destination.is_symlink() and os.readlink(destination) == target

  # follow_symlinks=False: a pre-existing entry must be backed up before replacement,
  # including an already-correct symlink in self-host mode. Source checkouts can track
  # those symlinks, so uninstall must restore them rather than remove them permanently.
  backup_record: BackupRecord | None
  already_tracked = known_backup is not None and known_backup.path == relative(repo_root, backup)
  should_backup_existing = destination.exists(follow_symlinks=False) and (
    not already_linked or (backup_existing and not already_tracked)
  )
  if should_backup_existing:
    backup_record = create_backup(repo_root, destination, backup, operation_log)
    already_linked = False
  else:
    backup_record = migrate_legacy_backup(repo_root, known_backup, backup)

  if already_linked:
    operation_log.add(f"ok {relative(repo_root, destination)}")
    return backup_record

  if operation_log.dry_run:
    operation_log.add(f"would link {relative(repo_root, destination)} -> {target}")
    return backup_record

  destination.parent.mkdir(parents=True, exist_ok=True)
  if destination.exists() or destination.is_symlink():
    destination.unlink()
  destination.symlink_to(target)
  operation_log.add(f"linked {relative(repo_root, destination)} -> {target}")
  return backup_record


def ensure_dir(repo_root: Path, path: Path, operation_log: OperationLog) -> None:
  if path.exists():
    if not path.is_dir():
      raise DotagentsError(f"expected directory: {relative(repo_root, path)}")
    return
  if operation_log.dry_run:
    operation_log.add(f"would create {relative(repo_root, path)}")
    return
  path.mkdir(parents=True)
  operation_log.add(f"created {relative(repo_root, path)}")


def resolve_within_root(repo_root: Path, path: Path) -> Path:
  """Resolve `path` and confirm it stays within `repo_root`, following any symlinked parents.

  Lockfile-sourced destinations are validated lexically at parse time
  (`validate_contained_relative_path`), but that catches only `..`/absolute-path strings —
  not an intermediate directory that is itself a symlink pointing outside root. This closes
  that gap at the point of actual filesystem use.

  Raises:
    DotagentsError: if `path` resolves outside `repo_root`.
  """
  resolved = path.resolve()
  if not resolved.is_relative_to(repo_root.resolve()):
    raise DotagentsError(f"path escapes root via symlink: {relative(repo_root, path)}")
  return resolved


def resolve_parent_within_root(repo_root: Path, path: Path) -> None:
  """Confirm `path`'s parent directory chain stays within `repo_root`, without resolving `path`.

  For operations that rename or unlink a symlink entry directly (never open or follow it) —
  `resolve_within_root` would incorrectly reject a legitimate symlink whose own target lies
  outside root (e.g. a backed-up `CLAUDE.md -> ~/notes.md`), since `Path.resolve()` dereferences
  the final path component too, not just its parents.

  Raises:
    DotagentsError: if `path`'s parent directory resolves outside `repo_root`.
  """
  resolved_parent = path.parent.resolve()
  if not resolved_parent.is_relative_to(repo_root.resolve()):
    raise DotagentsError(f"path escapes root via symlink: {relative(repo_root, path)}")


def remove_locked_link(
  repo_root: Path, destination: Path, expected_target: str, operation_log: OperationLog
) -> bool:
  """Return True if the link was removed (or would be in dry-run), False if skipped.

  Raises:
    DotagentsError: if `destination`'s parent directory resolves outside `repo_root`.
  """
  resolve_parent_within_root(repo_root, destination)
  display = relative(repo_root, destination)
  if not destination.exists() and not destination.is_symlink():
    operation_log.add(f"missing {display}")
    return True
  if not destination.is_symlink():
    operation_log.add(f"skip user-owned {display}; remove manually after verifying")
    return False

  actual_target = os.readlink(destination)
  if actual_target != expected_target:
    operation_log.add(f"skip unexpected symlink {display}; remove manually after verifying")
    return False

  if operation_log.dry_run:
    operation_log.add(f"would remove {display}")
    operation_log.pending_removals.add(destination)
    return True
  destination.unlink()
  operation_log.add(f"removed {display}")
  return True


def restore_backup(
  repo_root: Path,
  backup_path: Path,
  destination: Path,
  operation_log: OperationLog,
  expected_fingerprint: str | None = None,
) -> None:
  """Rename `backup_path` onto `destination`.

  Skips (with a log entry, no exception) if the backup is missing, not a regular file,
  directory, or symlink, or its fingerprint doesn't match `expected_fingerprint`.

  Raises:
    DotagentsError: if `backup_path` or `destination`'s parent directory resolves outside
      `repo_root`.
  """
  resolve_parent_within_root(repo_root, backup_path)
  resolve_parent_within_root(repo_root, destination)
  if not backup_path.exists(follow_symlinks=False):
    operation_log.add(f"backup missing {relative(repo_root, backup_path)}; skipped restore")
    return
  if not backup_path.is_symlink() and not backup_path.is_file():
    if (
      backup_path.is_dir()
      and expected_fingerprint
      and expected_fingerprint.startswith("directory:")
    ):
      pass
    else:
      # A directory or FIFO at the backup path — swapped in after backup creation, or a
      # legacy backup with no fingerprint to check. Never rename an untrusted non-regular
      # entry onto a managed destination, and never let backup_fingerprint() below open it
      # (IsADirectoryError, or a hang on a FIFO with no writer).
      operation_log.add(
        f"backup is not a file or symlink {relative(repo_root, backup_path)}; "
        "skipped restore, resolve manually"
      )
      return

  def fingerprint_mismatch() -> tuple[bool, str | None]:
    if expected_fingerprint is None:
      return False, None
    actual_fingerprint = backup_fingerprint(backup_path)
    return actual_fingerprint != expected_fingerprint, actual_fingerprint

  mismatch, actual_fingerprint = fingerprint_mismatch()
  if mismatch:
    operation_log.add(
      f"backup fingerprint mismatch {relative(repo_root, backup_path)}; "
      f"expected {expected_fingerprint}, found {actual_fingerprint}; "
      "skipped restore, resolve manually"
    )
    return
  if operation_log.dry_run:
    operation_log.add(
      f"would restore {relative(repo_root, backup_path)} -> {relative(repo_root, destination)}"
    )
    return
  # Re-verify immediately before the mutation. Directory fingerprinting requires a full
  # recursive walk, which widens the window between "checked" and "renamed" compared to a
  # single file's hash — this doesn't eliminate the race (no OS-level atomicity is used, and
  # the same race exists between this check and the rename call below), but shrinks it to
  # the minimum achievable without one.
  mismatch, actual_fingerprint = fingerprint_mismatch()
  if mismatch:
    operation_log.add(
      f"backup fingerprint mismatch {relative(repo_root, backup_path)}; "
      f"expected {expected_fingerprint}, found {actual_fingerprint}; "
      "skipped restore, resolve manually"
    )
    return
  backup_path.rename(destination)
  operation_log.add(
    f"restored {relative(repo_root, backup_path)} -> {relative(repo_root, destination)}"
  )


def restore_runtime_backup(
  repo_root: Path,
  backup_path: Path,
  destination: Path,
  operation_log: OperationLog,
  expected_fingerprint: str | None = None,
) -> None:
  """Restore a self-host runtime backup only when generated output is gone.

  A changed generated runtime is user-owned until it is resolved explicitly. Leaving it
  in place avoids replacing those files with the older pre-install `.agents` tree.

  Raises:
    DotagentsError: if a filesystem path escapes `repo_root`.
  """
  if operation_log.dry_run:
    if destination not in operation_log.pending_removals:
      operation_log.add(
        f"skip restoring {relative(repo_root, backup_path)}; "
        f"{relative(repo_root, destination)} still contains managed or changed files; "
        "resolve manually"
      )
      return
    restore_backup(repo_root, backup_path, destination, operation_log, expected_fingerprint)
    return
  if destination.exists(follow_symlinks=False):
    if destination.is_symlink() or not destination.is_dir() or any(destination.iterdir()):
      operation_log.add(
        f"skip restoring {relative(repo_root, backup_path)}; "
        f"{relative(repo_root, destination)} still contains managed or changed files; "
        "resolve manually"
      )
      return
    destination.rmdir()
  restore_backup(repo_root, backup_path, destination, operation_log, expected_fingerprint)


def remove_link_with_backup(
  repo_root: Path, link: LockedLink, destination: Path, operation_log: OperationLog
) -> bool:
  """Remove a locked link and restore its backup on success. Return whether it was removed.

  Raises:
    DotagentsError: if `destination` or the link's backup's parent directory resolves
      outside `repo_root`.
  """
  removed = remove_locked_link(repo_root, destination, link.target, operation_log)
  if removed and link.backup:
    restore_backup(
      repo_root, repo_root / link.backup, destination, operation_log, link.backup_fingerprint
    )
  return removed


def remove_locked_asset(
  repo_root: Path, path: Path, expected_sha256: str, operation_log: OperationLog
) -> bool:
  """Return True if the asset was removed (or would be in dry-run), False if skipped.

  Raises:
    DotagentsError: if `path` resolves outside `repo_root`.
  """
  resolve_parent_within_root(repo_root, path)
  display = relative(repo_root, path)
  if not path.exists() and not path.is_symlink():
    operation_log.add(f"missing {display}")
    return True
  if path.is_symlink() or not path.is_file():
    operation_log.add(f"skip unexpected {display}; remove manually after verifying")
    return False
  if sha256_file(path) != expected_sha256:
    operation_log.add(f"skip changed {display}; remove manually after verifying")
    return False

  if operation_log.dry_run:
    operation_log.add(f"would remove {display}")
    operation_log.pending_removals.add(path)
    return True
  path.unlink()
  operation_log.add(f"removed {display}")
  return True


def remove_generated_rules(
  repo_root: Path,
  operation_log: OperationLog,
  rules_backup: str | None,
  rules_backup_fingerprint: str | None = None,
) -> None:
  """Remove a dotagents-generated `.rules` and restore `rules_backup`, if any.

  Skips (with a log entry, no exception) if `.rules` is missing, unexpected, unreadable, or
  user-owned (no dotagents marker comment).

  Raises:
    DotagentsError: if (via `restore_backup`) `rules_backup` resolves outside `repo_root`.
  """
  rules = repo_root / ".rules"
  display = relative(repo_root, rules)
  if not rules.exists() and not rules.is_symlink():
    operation_log.add(f"missing {display}")
    if rules_backup:
      restore_backup(
        repo_root, repo_root / rules_backup, rules, operation_log, rules_backup_fingerprint
      )
    return
  if rules.is_symlink() or not rules.is_file():
    operation_log.add(f"skip unexpected {display}; remove manually after verifying")
    return
  try:
    content = rules.read_text(encoding="utf-8")
  except OSError:
    operation_log.add(f"skip unreadable {display}; remove manually after verifying")
    return
  if "<!-- Shared agent rules from dotagents package rules/rules.md -->" not in content:
    operation_log.add(f"skip user-owned {display}; remove manually after verifying")
    return

  if operation_log.dry_run:
    operation_log.add(f"would remove {display}")
    operation_log.pending_removals.add(rules)
  else:
    rules.unlink()
    operation_log.add(f"removed {display}")

  if rules_backup:
    restore_backup(
      repo_root, repo_root / rules_backup, rules, operation_log, rules_backup_fingerprint
    )


def remove_lockfile(repo_root: Path, lock_path: Path, operation_log: OperationLog) -> None:
  display = relative(repo_root, lock_path)
  if not lock_path.exists():
    operation_log.add(f"missing {display}")
    return
  if not lock_path.is_file():
    operation_log.add(f"skip unexpected {display}; remove manually after verifying")
    return

  if operation_log.dry_run:
    operation_log.add(f"would remove {display}")
    operation_log.pending_removals.add(lock_path)
    return
  lock_path.unlink()
  operation_log.add(f"removed {display}")


def collect_parents(repo_root: Path, path: Path, candidates: set[Path]) -> None:
  current = path.parent
  while current != repo_root and repo_root in current.parents:
    candidates.add(current)
    current = current.parent


def prune_empty_dirs(repo_root: Path, candidates: set[Path], operation_log: OperationLog) -> None:
  for path in sorted(candidates, key=lambda item: len(item.parts), reverse=True):
    if path == repo_root or not path.exists() or not path.is_dir():
      continue
    display = relative(repo_root, path)
    if operation_log.dry_run:
      remaining = [child for child in path.iterdir() if child not in operation_log.pending_removals]
      if not remaining:
        operation_log.add(f"would remove empty {display}")
        operation_log.pending_removals.add(path)
    else:
      try:
        next(path.iterdir())
      except StopIteration:
        path.rmdir()
        operation_log.add(f"removed empty {display}")


def relative(base: Path, path: Path) -> str:
  try:
    return os.path.relpath(path, base)
  except ValueError:
    return str(path)
